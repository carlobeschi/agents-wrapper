#!/usr/bin/env node
// Builds atlas-data.js (loaded by index.html) from layout.json and fields/*.json.
// Run: node atlas/build.js
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const layout = JSON.parse(fs.readFileSync(path.join(dir, 'layout.json'), 'utf8'));
const byId = {};
for (const file of fs.readdirSync(path.join(dir, 'fields')).filter(f => f.endsWith('.json'))) {
  const data = JSON.parse(fs.readFileSync(path.join(dir, 'fields', file), 'utf8'));
  for (const f of data.fields || [data]) byId[f.id] = f;
}

const problems = [];
const fields = layout.order.map(id => {
  const f = byId[id];
  if (!f) { problems.push(`missing field ${id}`); return null; }
  if (!layout.positions[id]) problems.push(`no position for ${id}`);
  for (const r of f.regions) {
    if (!(r.activity >= 1 && r.activity <= 5)) problems.push(`${r.id}: activity ${r.activity}`);
    if (!['frontier', 'emerging', 'adopting', 'established'].includes(r.maturity)) problems.push(`${r.id}: maturity ${r.maturity}`);
    r.landmarks = r.landmarks || [];
  }
  return f;
}).filter(Boolean);

const regionIds = new Set(fields.flatMap(f => f.regions.map(r => r.id)));
const routes = layout.routes.filter(r => {
  const ok = regionIds.has(r.from) && regionIds.has(r.to);
  if (!ok) problems.push(`route dropped: ${r.from} -> ${r.to}`);
  return ok;
});

// Threads and viewpoints: lists of region ids; "field.*" means every region of that field.
const expand = (kind, list) => (list || []).map(c => {
  const regions = [];
  for (const id of c.regions) {
    if (id.endsWith('.*')) { const f = fields.find(x => x.id === id.slice(0, -2)); if (f) regions.push(...f.regions.map(r => r.id)); else problems.push(`${kind} ${c.id}: unknown field ${id}`); }
    else if (regionIds.has(id)) regions.push(id);
    else problems.push(`${kind} ${c.id}: unknown region ${id}`);
  }
  return { id: c.id, name: c.name, blurb: c.blurb, regions: [...new Set(regions)] };
});
const themes = expand('thread', layout.themes), lenses = expand('viewpoint', layout.lenses);

const badUrl = u => u && !/^https?:\/\//.test(u);
for (const f of fields) {
  for (const d of f.deepDives || []) if (badUrl(d.url) || !d.url) problems.push(`${f.id}: deep dive without a valid url`);
  for (const r of f.regions) {
    for (const d of r.deepDives || []) if (badUrl(d.url) || !d.url) problems.push(`${r.id}: deep dive without a valid url`);
    for (const l of r.landmarks) if (badUrl(l.source)) problems.push(`${r.id}: bad source url for "${l.name}"`);
  }
}

const out = { title: layout.title, asOf: layout.asOf, world: layout.world, layout: layout.positions, fields, routes, themes, lenses };
fs.writeFileSync(path.join(dir, 'atlas-data.js'),
  '// Generated by atlas/build.js from layout.json and fields/*.json. Edit those, then rebuild.\n' +
  'window.ATLAS = ' + JSON.stringify(out, null, 1) + ';\n');

const lms = fields.flatMap(f => f.regions.flatMap(r => r.landmarks));
console.log(`${fields.length} fields, ${regionIds.size} regions, ${lms.length} landmarks (${lms.filter(l => !l.verified).length} unconfirmed), ${routes.length} routes`);
if (problems.length) console.log('Problems:\n  ' + problems.join('\n  '));
